"use strict";
/* Guided courses — "צריך עזרה?": level map → lesson → level quiz → summary.
   Ported from machine-learning-quiz/course-ui.js and adapted to this app's engine (option objects with ids,
   pre-rendered HTML with MathML, bidi.js isolates). Levels come from courses/<course>/*.js via courses.js
   (window.COURSES[id].levels), generated by tools/build_courses.py. The quiz runs on the main engine in app.js
   (S, renderQuestion, choose, next) with S.mode = "course"; app.js calls back into window.COURSE.record /
   finishLevel / exit. Each course keeps its progress in its own localStorage key, apart from the bank stats.

   level    = {id, order, icon, title, titleHtml, goal, goalHtml, boss?, lessonHtml, questions:[…]}
   question = {id, questionHtml, options:[{id,type,value,html}], correctId, explanationHtml, recapHtml}
            | {bankId:"<bank question id>", recapHtml, explanationHtml?}   ← a real exam question, verbatim
   An exam question id (e.g. 24X-A-Q9) anywhere in a lesson or explanation becomes a button that opens it. */
(function(){
  const META = {
    fa:       { name: "אוטומטים סופיים וביטויים", title: "צריך עזרה באוטומטים סופיים ובביטויים רגולריים?", icon: "🔀", store: "afq_crs_fa_v1",
                topics: ["dfa", "nfa", "regex"],
                intro: "מהרצת אס״ד על מילה ועד המרת אוטומט לביטוי רגולרי: אס״ד ואסל״ד, מסעי ε, אוטומט החזקה, ביטויים רגולריים והשוואה ביניהם. כל שלב פותח בשיעור קצר שבנוי על המבחנים הקודמים וממשיך בשאלות בסגנון המבחן. כל השלבים פתוחים; שלב נחשב עבור מ-80%." },
    nerode:   { name: "נרוד ומינימיזציה", title: "צריך עזרה בנרוד, Rank ומינימיזציה?", icon: "📏", store: "afq_crs_nerode_v1",
                topics: ["nerode"],
                intro: "הנושא הכבד בקורס, צעד אחר צעד: סיפא מפרידה, מחלקות שקילות, כמה מצבים באס״ד המינימלי, קבוצה מפרידה, Rank של פעולות על שפות, ו-Rank אינסופי. כל שלב פותח בשיעור קצר שבנוי על המבחנים הקודמים וממשיך בשאלות בסגנון המבחן. כל השלבים פתוחים; שלב נחשב עבור מ-80%." },
    classify: { name: "סיווג שפות", title: "צריך עזרה בסיווג שפות ובלמת הניפוח?", icon: "🗂️", store: "afq_crs_classify_v1",
                topics: ["classify", "pumping_reg", "reg_closure", "cfl_props"],
                intro: "הנושא הגדול בבנק: סופית, רגולרית, חסרת הקשר או לא. אלגוריתם סיווג, שפות שנראות קשות ובעצם רגולריות, הוכחת אי-רגולריות, משחק למת הניפוח, שפות מקוננות מול חוצות, וסגירות. כל שלב פותח בשיעור קצר שבנוי על המבחנים הקודמים וממשיך בשאלות בסגנון המבחן. כל השלבים פתוחים; שלב נחשב עבור מ-80%." },
    cf:       { name: "דקדוקים ואוטומט מחסנית", title: "צריך עזרה בדקדוקים חסרי הקשר ובאוטומט מחסנית?", icon: "🥞", store: "afq_crs_cf_v1",
                topics: ["cfg", "pda"],
                intro: "מקריאת דקדוק ועד אוטומט מחסנית בגודל של מבחן: פענוח דקדוק, איזה דקדוק יוצר את השפה, צורת חומסקי ודקדוק ליניארי, רב-משמעיות, ריצה של אוטומט מחסנית עם המוסכמה של מחסנית ריקה, ומציאת השפה של אוטומט. כל שלב פותח בשיעור קצר שבנוי על המבחנים הקודמים וממשיך בשאלות בסגנון המבחן. כל השלבים פתוחים; שלב נחשב עבור מ-80%." },
  };
  const PASS = 80;
  const ALL = window.COURSES || {};
  const screen = document.getElementById("screen-course");
  if (!screen) return;
  const has = id => ALL[id] && ALL[id].levels && ALL[id].levels.length;
  Object.keys(META).forEach(id => { if (!has(id)) document.querySelectorAll(`[data-course="${id}"]`).forEach(el => el.style.display = "none"); });
  if (!Object.keys(META).some(has)) { const h = document.getElementById("crsHub"); if (h) h.style.display = "none"; }

  let C = null;            // the open course: {id, meta, levels, prog}
  let cur = null, run = null;   // the level being played, and its answers {qid: ok}
  const prog = {};
  function load(id){
    try { const p = JSON.parse(localStorage.getItem(META[id].store)); if (p && p.levels && typeof p.levels === "object") return p; } catch(e){}
    return { levels:{} };
  }
  function save(){ try { localStorage.setItem(C.meta.store, JSON.stringify(C.prog)); } catch(e){} }
  function course(id){ prog[id] = prog[id] || load(id); return { id, meta: META[id], levels: ALL[id].levels, prog: prog[id] }; }

  const views = ["crsMapView", "crsLessonView", "crsSumView"];
  function view(id){ show("screen-course"); views.forEach(v => document.getElementById(v).classList.toggle("hidden", v !== id)); }
  const passedIn = (c, L) => ((c.prog.levels[L.id] || {}).best || 0) >= PASS;
  const passed = L => passedIn(C, L);
  const recommendedIn = c => c.levels.find(L => !passedIn(c, L));
  const levelName = L => `שלב ${L.order} · ${L.title}`;
  const backToMode = () => { S.mode = (document.querySelector('input[name=mode]:checked') || {}).value || "practice"; };

  /* ---------- rendering helpers ---------- */
  // All text arrives as HTML already (MathML built at build time). bidi.js wraps the Latin / digit runs inside
  // Hebrew in LTR isolates; math, code and existing isolates are left alone.
  const bidi = h => window.bidiHtml ? window.bidiHtml(h) : h;
  const textHtml = s => bidi(escapeHtml(String(s == null ? "" : s)));
  const QID = /\b[A-Z0-9]+(?:-[A-Z0-9]+)?-Q\d+\b/g;
  const bankIds = new Set(QS.map(q => q.id));
  // exam question ids → peek buttons (only ids that exist in the bank). While a level is played, the
  // real exam questions it has not asked yet stay plain text: the peek would show their answer.
  let unasked = new Set();
  function linkRefs(html){
    return html.replace(/<[^>]+>|[^<]+/g, t => t[0] === "<" ? t :
      t.replace(QID, m => bankIds.has(m) && !unasked.has(m) ? `<button type="button" class="qref" data-q="${m}">${m}</button>` : m));
  }
  const rich = h => linkRefs(bidi(String(h == null ? "" : h)));
  window.crsRich = rich;   // app.js uses it for the feedback of a course question
  const titleH = L => bidi(L.titleHtml || escapeHtml(L.title || ""));
  const goalH = L => bidi(L.goalHtml || escapeHtml(L.goal || ""));
  // lesson html: wrap tables for sideways scroll on phones, link exam ids, isolate Latin runs
  function lessonHtml(html){
    return linkRefs(bidi(String(html || "").replace(/<table\b/g, '<div class="tbl-wrap"><table').replace(/<\/table>/g, "</table></div>")));
  }

  /* ---------- map ---------- */
  function renderMap(){
    const LV = C.levels, rec = recommendedIn(C), nPass = LV.filter(passed).length;
    $("#crsTitle").textContent = `${C.meta.icon} ${C.meta.title}`;
    $("#crsIntro").textContent = C.meta.intro;
    $("#crsOverall").innerHTML =
      `עברת <b>${nPass}</b> מתוך <b>${LV.length}</b> שלבים` +
      `<div class="progress" style="margin-top:.5rem"><div class="progress-fill" style="width:${nPass / LV.length * 100}%"></div></div>` +
      (nPass === LV.length ? `<p style="margin:.6rem 0 0">🏆 סיימת את כל הקורס. הצעד הבא: שאלות ${C.meta.name} מהמבחנים.</p>` : "");
    $("#crsMap").innerHTML = LV.map(L => {
      const st = C.prog.levels[L.id];
      const cls = ["crs-lvl", passed(L) ? "passed" : "", L === rec ? "next" : "", L.boss ? "boss" : ""].join(" ").replace(/\s+/g, " ").trim();
      const status = !st ? `עוד לא התחלת · ${L.questions.length} שאלות`
        : passed(L) ? `✓ עברת · שיא ${st.best}%` : `ניסיון אחרון ${st.last}% · שיא ${st.best}% (צריך ${PASS}%)`;
      return `<button class="${cls}" data-id="${L.id}" type="button">
        <span class="num">שלב ${L.order}${L.boss ? " · מבחן גמר" : ""}</span>
        <span class="ttl">${L.icon || ""} ${titleH(L)}</span>
        <span class="gl">${goalH(L)}</span>
        <span class="st">${status}</span></button>`;
    }).join("");
    $("#crsMap").querySelectorAll(".crs-lvl").forEach(b => b.onclick = () => openLesson(LV.find(L => L.id === b.dataset.id)));
  }
  function openMap(id){ if (id) C = course(id); cur = null; renderMap(); view("crsMapView"); }

  /* ---------- lesson ---------- */
  function openLesson(L){
    cur = L;
    const nReal = L.questions.filter(q => q.bankId).length;
    $("#crsLesson").innerHTML =
      `<div class="q-head"><span class="chip">שלב ${L.order} מתוך ${C.levels.length}</span><span class="chip soft">${L.questions.length} שאלות${nReal ? ` · ${nReal} מהמבחנים` : ""}</span></div>` +
      `<h2 class="learn-h">${L.icon || ""} ${titleH(L)}</h2><p class="sub crs-goal">${goalH(L)}</p>` +
      (window.VIDEO_UI ? window.VIDEO_UI.lessonButtons(L.id) : "") +   // video-ui.js: "▶ צפו בסרטון של הרמה"
      `<div class="lesson-body">${lessonHtml(L.lessonHtml)}</div>`;
    view("crsLessonView");
    if (typeof markWide === "function") markWide($("#crsLesson"));
  }

  /* ---------- level quiz (runs on the main engine) ---------- */
  // a level question in engine form: the bank shape ({options:[{id,html}], correctId}); bank refs are cloned from the bank
  function engineQ(q, L){
    const levelTitle = levelName(L), badge = `${C.meta.icon} ${C.meta.name}`;
    let base;
    if (q.bankId){
      const b = QS.find(x => x.id === q.bankId);
      base = Object.assign({}, b, { id: `${L.id}:${q.bankId}`, explanationHtml: q.explanationHtml || b.explanationHtml, recapHtml: q.recapHtml,
        fromExam: `${examLabelOf(b)}, שאלה ${b.num}`, examId: b.id });
    } else {
      base = Object.assign({ topic: C.meta.topics[0] }, q);
    }
    return Object.assign(base, { course: { courseId: C.id, levelId: L.id, levelTitle, badge } });
  }
  function startLevel(L){
    cur = L; run = {};
    unasked = new Set(L.questions.filter(q => q.bankId).map(q => q.bankId));
    S.mode = "course"; S._views = null;
    S.pool = L.questions.map(q => engineQ(q, L));
    S.pos = 0; S.hist = []; S.hpos = 0; S.streak = 0;
    $("#prevBtn").classList.remove("hidden");
    show("screen-quiz");
    renderQuestion();
  }
  function record(q, ok){ if (q.examId) unasked.delete(q.examId); if (run && !(q.id in run)) run[q.id] = ok; }

  function finishLevel(){
    const L = cur; if (!L) return openMap();
    const qs = S.pool, total = qs.length;
    const correct = qs.filter(q => run && run[q.id]).length;
    const pct = Math.round(correct / total * 100);
    const prev = C.prog.levels[L.id] || {};
    C.prog.levels[L.id] = { best: Math.max(prev.best || 0, pct), last: pct, at: Date.now() };
    save();
    const ok = pct >= PASS, LV = C.levels, nextL = LV[LV.indexOf(L) + 1];
    const wrong = qs.filter(q => !(run && run[q.id]));
    unasked = new Set();
    backToMode();
    $("#crsSum").innerHTML =
      `<div class="q-head" style="justify-content:center"><span class="chip">${bidi(escapeHtml(levelName(L)))}</span></div>` +
      `<div class="big">${pct}%</div><div><b><bdi dir="ltr">${correct} / ${total}</bdi></b> תשובות נכונות</div>` +
      `<p class="msg">${ok ? (L.boss ? `🏆 עברת את מבחן הגמר של ${C.meta.name}!` : "✓ עברת את השלב! אפשר להתקדם.") :
        "עוד לא 80%. כדאי לקרוא שוב את השיעור ולנסות שוב, זה בדיוק השלב שבו זה נבנה."}</p>` +
      (wrong.length ? `<div class="crs-review"><div class="crs-review-t">כדאי לחזור על:</div>${
        wrong.map(q => `<div>• ${rich(q.recapHtml || q.questionHtml)}</div>`).join("")}</div>` : "") +
      `<div class="crs-actions">` +
        (nextL ? `<button class="btn ${ok ? "primary" : "ghost"}" data-act="next">לשלב הבא: ${titleH(nextL)} ⟵</button>` : "") +
        (L.boss || !nextL ? `<button class="btn primary" data-act="real">לשאלות ${C.meta.name} מהמבחנים האמיתיים ⟵</button>` : "") +
        `<button class="btn ${ok ? "ghost" : "primary"}" data-act="retry">🔁 לנסות שוב</button>` +
        `<button class="btn ghost" data-act="lesson">📘 לשיעור</button>` +
        `<button class="btn ghost" data-act="map">🗺️ למפת השלבים</button>` +
      `</div>`;
    $("#crsSum").querySelectorAll("[data-act]").forEach(b => b.onclick = () => {
      const a = b.dataset.act;
      if (a === "next") openLesson(nextL);
      else if (a === "retry") startLevel(L);
      else if (a === "lesson") openLesson(L);
      else if (a === "real") realExam();
      else openMap();
    });
    view("crsSumView");
  }
  function exit(){ unasked = new Set(); backToMode(); S.hist = []; S.hpos = 0; cur ? openLesson(cur) : openMap(); }

  // hand off to the real exam questions of this course's topics (free practice)
  function realExam(){
    const r = document.querySelector('input[name=mode][value="practice"]'); if (r) r.checked = true;
    $("#examOpts").classList.add("hidden");
    ["#officialOnly", "#mistakesOnly"].forEach(s => { const el = $(s); if (el) el.checked = false; });
    S.mode = "practice"; S._views = null;
    S.pool = shuffle(dedupePool(QS.filter(q => C.meta.topics.includes(q.topic))));
    S.pos = 0; S.hist = []; S.hpos = 0; S.streak = 0;
    $("#prevBtn").classList.remove("hidden");
    show("screen-quiz");
    renderQuestion();
  }

  /* ---------- wiring ---------- */
  $("#crsLessonGo").onclick = () => cur && startLevel(cur);
  $("#crsLessonBack").onclick = () => openMap();
  $("#crsHomeBtn").onclick = () => quit();
  $("#crsResetBtn").onclick = () => { if (confirm(`לאפס את ההתקדמות בקורס ${C.meta.name}?`)){ C.prog.levels = {}; save(); renderMap(); } };
  function paintPromos(){
    document.querySelectorAll(".crs-promo[data-course]").forEach(el => {
      const id = el.dataset.course; if (!has(id)) return;
      const c = course(id), n = c.levels.filter(L => passedIn(c, L)).length, rec = recommendedIn(c);
      const sub = el.querySelector(".crs-promo-sub");
      if (!sub.dataset.base) sub.dataset.base = sub.textContent;
      sub.textContent = n ? `עברת ${n} מתוך ${c.levels.length} שלבים${rec ? ". הבא בתור: " + rec.title : ". סיימת, כל הכבוד!"}` : sub.dataset.base;
    });
  }
  document.querySelectorAll("[data-course]").forEach(el => {
    const id = el.dataset.course; if (!has(id)) return;
    el.onclick = () => openMap(id);
    if (el.classList.contains("crs-promo"))
      el.onkeydown = e => { if (e.key === "Enter" || e.key === " "){ e.preventDefault(); openMap(id); } };
  });
  paintPromos();
  window.addEventListener("afq:home", paintPromos);

  // exam-id buttons inside a lesson, the answer feedback or the summary open the question peek
  document.addEventListener("click", e => {
    const b = e.target.closest(".qref"); if (!b || b.closest("#learnContent")) return;
    if (window.openQPeek) window.openQPeek(b.dataset.q);
  });

  // header: one entry that brings you to the course cards on the home screen
  const hub = $("#crsHub");
  if (hub) hub.onclick = () => { quit(); setTimeout(() => { const p = $(".crs-promos"); if (p) p.scrollIntoView({ behavior: "smooth", block: "start" }); }, 60); };

  window.COURSE = { record, finishLevel, exit, openMap, openLesson: L => openLesson(L), startLevel: L => startLevel(L), META };

  // deep link: ?course=fa (map) · ?course=fa&level=F03 (that lesson) · …&play=1 (its quiz)
  try {
    const p = new URLSearchParams(location.search), id = p.get("course");
    if (id && has(id)){
      C = course(id);
      const L = C.levels.find(l => l.id === p.get("level"));
      if (!L) openMap(); else if (p.get("play")) startLevel(L); else openLesson(L);
    }
  } catch(e){}
})();

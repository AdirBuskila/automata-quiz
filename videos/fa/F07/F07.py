def same(r, D, alpha):
    x = rx(r, alpha)
    return x.dfa().equiv(D) and x.lang(8) == D.lang(8)


# ---------------------------------------------------------------- machines (verified)
D3 = dfa_table("ab", {"0": "1 0", "1": "2 0", "2": "2 2"}, "0", {"0"})      # every a is immediately followed by b
assert D3.lang(8) == {w for w in words("ab", 8) if all(w[i + 1:i + 2] == "b" for i, c in enumerate(w) if c == "a")}
assert same("(b+ab)*", D3, "ab")
TRAP1 = "(ab)*b*"                                                          # rounds in a fixed order
assert not same(TRAP1, D3, "ab") and D3.accepts("bab") and not rx(TRAP1, "ab").accepts("bab")

DE = dfa_table("01", {"0": "0 1", "1": "0 1"}, "0", {"1"})
assert DE.lang(8) == {w for w in words("01", 8) if w.endswith("1")}
assert same("0*1(1+00*1)*", DE, "01")
assert DE.run("10") == "0" and not DE.accepts("10")                        # a half round is not in L
assert not same("0*1(1+00*)*", DE, "01") and rx("0*1(1+00*)*", "01").accepts("10")


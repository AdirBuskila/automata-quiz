# ---------------------------------------------------------------- 2. 24X-A-Q13 (left state 1, right state 2)
Q2 = BANK["24X-A-Q13"]
D2 = dfa_table("ab", {"1": "2 1", "2": "1 2"}, "1", {"2"})
assert D2.lang(8) == {w for w in words("ab", 8) if w.count("a") % 2 == 1}
R2 = {"a": "b*a(ab*a+b)*", "b": "b*a(ab*a)*", "c": "b*a(b*+aba)*"}
same = lambda r: rx(r, "ab").dfa().equiv(D2)
assert [k for k, r in R2.items() if same(r)] == [Q2["correctId"]] == ["a"]
assert D2.accepts("abbb") and not rx(R2["b"], "ab").accepts("abbb")
assert D2.accepts("aabbba") and not rx(R2["c"], "ab").accepts("aabbba")

# ---------------------------------------------------------------- 3. 25A-C-Q9
Q3 = BANK["25A-C-Q9"]
G3 = "a*b(a+b)*b"
L3 = {w for w in words("ab", 8) if w.count("b") >= 2 and w.endswith("b")}

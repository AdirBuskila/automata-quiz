def ring_steps(pfx, word, sets):
    ph = []
    for i, c in enumerate(word):
        do = hide(*[f"{pfx}-ring-{q}" for q in sets[i]]) + show(*[f"{pfx}-ring-{q}" for q in sets[i + 1]])
        do += show(f"q1t-r-{i + 1}") + (hide(f"q1t-k-{i - 1}") + show(f"q1t-d-{i - 1}") if i else []) + show(f"q1t-k-{i}")
        if sets[i + 1]:
            say = f"{lexicon.word_say(c)}: {fa.set_say(sets[i + 1], NB)}."
        else:
            say = f"{lexicon.word_say(c)}: אין לאן ללכת."
        ph.append(P(f"${c}$: ${fa.set_tex(sets[i + 1], NB)}$", say=say, do=do))
    return ph



R3 = {"a": "(a*ba*b)*", "b": "a*ba*b*(a+b)*", "c": "(a+b)*b(a+b)*bb*"}
assert [k for k, r in R3.items() if rx(r, "ab").equiv(rx(G3, "ab"))] == [Q3["correctId"]] == ["c"]
assert rx(R3["a"], "ab").accepts("") and not rx(G3, "ab").accepts("")
assert rx(R3["b"], "ab").accepts("b") and not rx(G3, "ab").accepts("b")


# ---------------------------------------------------------------- machines (verified)
SE = nfa_from_edges("ab", [("0", "a", "1"), ("1", "a", "1"), ("1", "b", "1"), ("1", "b", "2")], "0", {"2"})
assert SE.lang(8) == {w for w in words("ab", 8) if len(w) >= 2 and w[0] == "a" and w[-1] == "b"}
D = SE.to_dfa()
F = frozenset
ROWS = [F({"0"}), F({"1"}), F(), F({"1", "2"})]                       # build order (first time each set appears)
assert D.reachable() == set(ROWS) and D.start == F({"0"})
EXP = {(F({"0"}), "a"): F({"1"}), (F({"0"}), "b"): F(), (F({"1"}), "a"): F({"1"}), (F({"1"}), "b"): F({"1", "2"}),
       (F(), "a"): F(), (F(), "b"): F(), (F({"1", "2"}), "a"): F({"1"}), (F({"1", "2"}), "b"): F({"1", "2"})}
assert all(D.delta[k] == v for k, v in EXP.items())
assert {R for R in D.reachable() if R in D.acc} == {F({"1", "2"})}
assert len(D.reachable()) == 4 < 2 ** 3 and D.n_min() == 4        # the ∅ sink is needed: 3 NFA states, 4 DFA states

# counting: n = 3, f = 1 (q2 accepting)
SUBS = [F(c) for k in range(4) for c in combinations("012", k)]
assert len(SUBS) == 8 and sum(1 for S in SUBS if "2" in S) == 2 ** 3 - 2 ** (3 - 1) == 4
assert 2 ** 3 - 2 ** 1 == 6 != 4                                       # the classic mistake 2^n - 2^f
for n in range(1, 7):                                                  # the formula on every (n, f) with n <= 6
    for f in range(n + 1):
        assert sum(1 for m in range(1 << n) if m & ((1 << f) - 1)) == 2 ** n - 2 ** (n - f)

# exam 21S-B-Q7: k-th letter from the end, k = 10 -> NFA with n = 11 states, minimal DFA 2^10 = 1024 > n^2 = 121
Q = BANK["21S-B-Q7"]
K = 10
KN = nfa_from_edges("01", [("0", "0", "0"), ("0", "1", "0"), ("0", "1", "1")]
                    + [(str(i), c, str(i + 1)) for i in range(1, K) for c in "01"], "0", {str(K)})
assert len(KN.states) == K + 1
assert all(KN.accepts(w) == (len(w) >= K and w[-K] == "1") for w in words("01", 12))
KMIN = KN.to_dfa().n_min()
assert KMIN == 2 ** K == 1024 > (K + 1) ** 2 == 121 and Q["correctId"] == "a"

# the course proof of the 2^k lower bound: all words of length k form a separating set
from itertools import product as _prod
from nh import is_separating_set
for k in (2, 4, 5):
    assert is_separating_set(lambda w, k=k: len(w) >= k and w[-k] == "1", ["".join(p) for p in _prod("01", repeat=k)], "01")


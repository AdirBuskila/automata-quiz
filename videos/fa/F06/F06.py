# ---------------------------------------------------------------- facts (verified)
def grid(r1, r2, ws, alpha):
    return [[rx(r1, alpha).accepts(w), rx(r2, alpha).accepts(w)] for w in ws]


def tex_w(ws):
    return [w if w else r"\varepsilon" for w in ws]


# example 1: strictly contained
E1 = ("a(a+b)*", "(a+b)*a(a+b)*")
W1 = ["", "aa", "bb", "abb", "ba"]
G1 = grid(*E1, W1, "ab")
assert rx_vs_rx(*E1, "ab") == "lt"
assert G1 == [[False, False], [True, True], [False, False], [True, True], [False, True]]
QUIZ_WORDS = {"abab", "aab", "ab", "a", "b", "101", "11", "0"}           # words of this level's quiz options
assert not set(W1[1:]) & QUIZ_WORDS

# example 2: neither (one word per direction)
E2 = ("(a+b)*bb", "(a+b)*aa")
W2 = ["", "aa", "bb"]
G2 = grid(*E2, W2, "ab")
assert rx_vs_rx(*E2, "ab") == "none" and G2 == [[False, False], [False, True], [True, False]]
assert not set(W2[1:]) & QUIZ_WORDS

# example 3 (lesson, 19B-B-Q2's pair): equal, and ε is in neither
E3 = ("10(10)*", "1(01)*0")
assert rx_vs_rx(*E3, "01") == "eq" and not rx(E3[0], "01").accepts("") and not rx(E3[1], "01").accepts("")
for k in range(5):
    assert "1" + "01" * k + "0" == "10" * (k + 1)

# exam 19B-A-Q2
Q = BANK["19B-A-Q2"]
X = ("(ab*)*ba*", "(a*ba*b)*a*")
assert rx_vs_rx(*X, "ab") == "none" and Q["correctId"] == "d"
WX = ["", "ba"]
GX = grid(*X, WX, "ab")
assert GX == [[False, True], [True, False]]
assert all("b" in w for w in rx(X[0], "ab").lang(8))                                   # every r1 word has a b
assert all(w.count("b") % 2 == 0 for w in rx(X[1], "ab").lang(8))                      # r2: even number of b


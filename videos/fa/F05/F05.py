# ---------------------------------------------------------------- facts (verified)
assert rx("ε", "ab").lang(6) == {""} and rx("∅", "ab").lang(6) == set()
PREC = rx("0+10*", "01")
assert PREC.lang(4) == {"0", "1", "10", "100", "1000"} and not PREC.accepts("00")
assert rx("(0+1)0*", "01").accepts("00")

ODD = rx("(ΣΣ)*1Σ*", "01")
assert ODD.lang(8) == {w for w in words("01", 8) if any(w[i] == "1" for i in range(0, len(w), 2))}
assert ODD.accepts("0010") and not ODD.accepts("0100") and ODD.accepts("1")

ONE = lambda w: w.count("b") == 1
CANDS = ["a*ba*", "(a+b)*b(a+b)*", "a*b"]
assert rx("a*ba*", "ab").lang(8) == {w for w in words("ab", 8) if ONE(w)}
GW = ["b", "ab", "ba", "bb"]
GRID = [[ONE(w)] + [rx(r, "ab").accepts(w) for r in CANDS] for w in GW]
assert GRID == [[True, True, True, True], [True, True, True, True], [True, True, True, False],
                [False, False, True, False]]

assert rx("(ab*+b)*", "ab").equiv(rx("(a+b)*", "ab"))      # (a*b*)* is F05 quiz Q5's answer: not used
assert rx("(a+b)*", "ab").accepts("ab") and not rx("a*+b*", "ab").accepts("ab")
assert rx("(ε+ab)(ab)*", "ab").equiv(rx("(ab)*", "ab"))

# exam 19B-B-Q7: words over {a,b} that do not end with ba
Q = BANK["19B-B-Q7"]
NOTBA = {w for w in words("ab", 8) if not w.endswith("ba")}
OPT = {"a": "b*a*(ab)*", "b": "(ε+a+b)+(a+b)(aa+ab+bb)*", "c": "((ε+a+b)(a+b))*(aa+ab+bb)",
       "d": "(ε+a+b)+(a+b)*(aa+ab+bb)"}
assert [k for k, r in OPT.items() if rx(r, "ab").lang(8) == NOTBA] == [Q["correctId"]] == ["d"]
assert "abb" in NOTBA and not rx(OPT["a"], "ab").accepts("abb")
assert "aa" in NOTBA and not rx(OPT["b"], "ab").accepts("aa")
assert "a" in NOTBA and not rx(OPT["c"], "ab").accepts("a")
assert {"", "a", "b"} <= NOTBA and all(rx(OPT["d"], "ab").accepts(w) for w in ["", "a", "b"])


# ---------------------------------------------------------------- worked example: contains ab
AB = lambda w: "ab" in w
D3 = dfa_table("ab", {"0": "1 0", "1": "1 2", "2": "2 2"}, "0", {"2"})
D4 = dfa_table("ab", {"0": "1 0", "1": "1 2", "2": "3 2", "3": "2 3"}, "0", {"2", "3"})   # correct, not minimal
for D in (D3, D4):
    assert D.lang(8) == {w for w in words("ab", 8) if AB(w)}
assert len(D4.states) == 4 and D4.n_min() == 3 == D3.n_min() == rank_stable(AB, "ab")
T = ["", "a", "ab"]
PC = pair_cells(AB, T, "ab")
assert PC == {(1, 0): "b", (2, 0): "", (2, 1): ""} and is_separating_set(AB, T, "ab")
TB = ["", "b", "ab"]
PCB = pair_cells(AB, TB, "ab")
assert PCB[(1, 0)] is None and not is_separating_set(AB, TB, "ab")
assert D3.run("") == D3.run("b") == "0"
assert is_separating_set(AB, ["", "a"], "ab")                       # separating, but only proves Rank >= 2
assert not any(is_separating_set(AB, T + [x], "ab") for x in words("ab", 5) if x not in T)   # no 4th word fits

# ---------------------------------------------------------------- exam 21S-A-Q9: sum of digits divisible by 3, over {0,1,2}
QA = BANK["21S-A-Q9"]
S3 = lambda w: sum(int(c) for c in w) % 3 == 0
assert rank_stable(S3, "012", 6, (3, 4, 5)) == 3
DS = dfa_table("012", {"0": "0 1 2", "1": "1 2 0", "2": "2 0 1"}, "0", {"0"})
assert DS.lang(6) == {w for w in words("012", 6) if S3(w)} and DS.n_min() == 3
OPT = {"a": ["", "11", "111"], "b": ["1", "22", "000"], "c": ["00", "11", "22"]}
SEPS = {k: is_separating_set(S3, v, "012", 5) for k, v in OPT.items()}
assert SEPS == {"a": False, "b": False, "c": True} and QA["correctId"] == "c"
assert separable(S3, "", "111", "012", 5) is None and separable(S3, "1", "22", "012", 5) is None
assert [DS.run(w) for w in OPT["c"]] == ["0", "2", "1"]
FAM = ["0" * d + "1" * d + "2" * d for d in range(5)]               # option d: infinite, all residue 0
assert all(DS.run(w) == "0" for w in FAM) and not is_separating_set(S3, FAM[:3], "012", 5)


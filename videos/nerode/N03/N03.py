R = lambda p, a="01": rank_stable(p, a, 9, (5, 6, 7))

# ends with 01: k + 1 = 3
E01 = lambda w: w.endswith("01")
DE = dfa_table("01", {"0": "1 0", "1": "1 2", "2": "1 0"}, "0", {"2"})
assert DE.lang(8) == {w for w in words("01", 8) if E01(w)} and DE.n_min() == 3 == R(E01)
TE = ["", "0", "01"]
PCE = pair_cells(E01, TE, "01")
assert PCE == {(1, 0): "1", (2, 0): "", (2, 1): ""}
assert DE.run("") == DE.run("1") == DE.run("11") == DE.run("0101" + "1") == "0"   # "nothing of the ending yet"
assert DE.run("0") == DE.run("100") == "1"

# starts with 01: k + 2 = 4
S01 = lambda w: w.startswith("01")
DS = dfa_table("01", {"0": "1 3", "1": "3 2", "2": "2 2", "3": "3 3"}, "0", {"2"})
assert DS.lang(8) == {w for w in words("01", 8) if S01(w)} and DS.n_min() == 4 == R(S01)
TS = ["", "0", "01", "1"]
assert is_separating_set(S01, TS, "01")

# k-th letter from the start / from the end is 1 (k = 2, 4)
KS = lambda k: (lambda w: len(w) >= k and w[k - 1] == "1")
KE = lambda k: (lambda w: len(w) >= k and w[-k] == "1")
assert R(KS(2)) == 4 and R(KE(2)) == 4
assert rank_stable(KS(4), "01", 9, (6, 7, 8)) == 6
assert rank_stable(KE(4), "01", 9, (6, 7, 8)) == 16
for k in (2, 3, 4):               # the proof on screen: words of length k, first difference at i, suffix 0^(i-1)
    for u in words("01", k):
        for v in words("01", k):
            if len(u) == len(v) == k and u != v:
                i = next(t for t in range(k) if u[t] != v[t]) + 1
                assert KE(k)(u + "0" * (i - 1)) != KE(k)(v + "0" * (i - 1))


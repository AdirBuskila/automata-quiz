END00 = lambda w: w.endswith("00")
EVEN1 = lambda w: w.count("1") % 2 == 0
END1 = lambda w: w.endswith("1")


def sep(pred, x, y, z):
    return pred(x + z) != pred(y + z)


def equiv(pred, x, y):
    return separable(pred, x, y, "01", 8) is None



def R(pred):
    return rank_stable(pred, "01", 9, (5, 6, 7))


END111 = lambda w: w.endswith("111")
SL0 = lambda w: len(w) >= 2 and w[-2] == "0"
SAME = lambda w: len(w) >= 2 and w[0] == w[-1]
PAR_OR = lambda w: w.count("0") % 2 == 0 or w.count("1") % 2 == 0
THIRD_START1 = lambda w: len(w) >= 3 and w[2] == "1"
THIRD_END1 = lambda w: len(w) >= 3 and w[-3] == "1"
STARTS1 = lambda w: w.startswith("1")
ENDS1 = lambda w: w.endswith("1")
ENDS00 = lambda w: w.endswith("00")
r = {k: R(v) for k, v in dict(e111=END111, sl0=SL0, same=SAME, par=PAR_OR, t_start=THIRD_START1, t_end=THIRD_END1,
                              s1=STARTS1, e1=ENDS1, e00=ENDS00).items()}
assert r == dict(e111=4, sl0=4, same=5, par=4, t_start=5, t_end=8, s1=3, e1=2, e00=3), r


def one_class(pred, inside):
    """all words (length <= 6) with pred(w) == inside lie in a single equivalence class"""
    cl = classes(pred, "01", 6, 8)
    idx = {w: i for i, c in enumerate(cl) for w in c}
    ids = {idx[w] for w in words("01", 6) if pred(w) == inside}
    return len(ids) == 1


def truths(pred):
    b, c = one_class(pred, True), one_class(pred, False)
    return {"a": False, "b": b, "c": c, "d": (not b) and (not c)}


def xy_options(pred):
    t = truths(pred)
    return [C(r"אם $y\in L$ ו-$x\notin L$ אז $x,y$ לא ניתנות להפרדה", t["a"]),
            C(r"אם $x,y\in L$ אז $x,y$ לא ניתנות להפרדה", t["b"]),
            C(r"אם $x,y\notin L$ אז $x,y$ לא ניתנות להפרדה", t["c"]),
            C("כל הטענות האחרות אינן נכונות", t["d"])]


def stem(desc):
    return (r"תהי $L$ שפת המילים מעל $\{0,1\}$ " + desc + r". יהיו $x\ne y$ שתי מילים כלשהן. איזו טענה נכונה?")


L_111 = lambda w: w.endswith("111")
L_NE = lambda w: w.count("0") != w.count("1")
L_PAL = lambda w: w == w[::-1]
L_LE = lambda w: w.count("0") <= w.count("1")
L_1S1 = lambda w: len(w) >= 2 and w[0] == "1" and w[-1] == "1"
assert truths(L_111) == {"a": False, "b": True, "c": False, "d": False}
assert truths(L_NE) == {"a": False, "b": False, "c": True, "d": False}
assert truths(L_PAL)["d"] and truths(L_LE)["d"]
assert truths(L_1S1)["b"] and not truths(L_1S1)["c"]


NS = list(range(2, 8))


def wins(pred, f, ns=NS):
    """the word family f(n) forces a contradiction for every constant n in ns (prover wins every round)"""
    return pump_word_works(pred, f, ns)


def abc(w):
    m = re.fullmatch(r"(a*)(b*)(c*)", w)
    return None if not m else tuple(len(g) for g in m.groups())


def ab(w):
    m = re.fullmatch(r"(a*)(b*)", w)
    return None if not m else tuple(len(g) for g in m.groups())


# Q1  L = a^k b^m c^k
L1 = lambda w: abc(w) is not None and abc(w)[0] == abc(w)[2]
Q1 = {"a^n b^n c^n": wins(L1, lambda n: "a" * n + "b" * n + "c" * n),
      "a b^n c": wins(L1, lambda n: "a" + "b" * n + "c"),
      "a^{n-1} b c^{n-1}": wins(L1, lambda n: "a" * (n - 1) + "b" + "c" * (n - 1)),
      "a^2 b^n c^2": wins(L1, lambda n: "aa" + "b" * n + "cc")}
assert Q1 == {"a^n b^n c^n": True, "a b^n c": False, "a^{n-1} b c^{n-1}": False, "a^2 b^n c^2": False}, Q1
# Q2  L = a^n b^m with n > m
L2 = lambda w: ab(w) is not None and ab(w)[0] > ab(w)[1]
Q2 = {"a^{n+1} b^n": wins(L2, lambda n: "a" * (n + 1) + "b" * n), "a^{n+2} b^n": wins(L2, lambda n: "a" * (n + 2) + "b" * n),
      "a^n b^n": wins(L2, lambda n: "a" * n + "b" * n), "a^{2n} b^n": wins(L2, lambda n: "a" * (2 * n) + "b" * n)}
assert Q2 == {"a^{n+1} b^n": True, "a^{n+2} b^n": False, "a^n b^n": False, "a^{2n} b^n": False}, Q2
# Q3  even palindromes w w^R
L3 = lambda w: len(w) % 2 == 0 and w == w[::-1]
Q3 = {"a^n bb a^n": wins(L3, lambda n: "a" * n + "bb" + "a" * n), "a^{2n}": wins(L3, lambda n: "a" * (2 * n)),
      "b a^{2n} b": wins(L3, lambda n: "b" + "a" * (2 * n) + "b"), "a^n b a^n": wins(L3, lambda n: "a" * n + "b" + "a" * n)}
assert Q3 == {"a^n bb a^n": True, "a^{2n}": False, "b a^{2n} b": False, "a^n b a^n": False}, Q3
# Q4  squares a^{k^2}   (the fixed-length word is exposed by a huge constant)
L4 = lambda w: int(len(w) ** 0.5) ** 2 == len(w)
BIG = NS + [150]
Q4 = {"a^{n^2}": wins(L4, lambda n: "a" * (n * n), BIG), "a^100": wins(L4, lambda n: "a" * 100, BIG),
      "a^{n^2+1}": wins(L4, lambda n: "a" * (n * n + 1), BIG), "a^{2n}": wins(L4, lambda n: "a" * (2 * n), BIG)}
assert Q4 == {"a^{n^2}": True, "a^100": False, "a^{n^2+1}": False, "a^{2n}": False}, Q4


# Q1  a^(2k): a one-state PDA, but the minimal DFA has 2 states
ONE = PDA([("0", "a", "", "0", "x"), ("0", "a", "x", "0", "")], "0", {"0"})
EVEN_A = {"a" * k for k in range(0, 13, 2)}
one_state = ONE.lang("a", 12) == EVEN_A
DFA2 = dfa_table("a", {"0": "1", "1": "0"}, "0", {"0"})
dfa_states = DFA2.n_min()
assert one_state and dfa_states == 2
# Q2  flipping the accepting states of an NFA does not complement the language
N1 = nfa_from_edges("ab", [], "0", {"0"})
FLIP = NFA("ab", {}, "0", frozenset())
comp_ok = all(FLIP.accepts(w) == (not N1.accepts(w)) for w in words("ab", 6))
assert not comp_ok and N1.lang(4) == {""} and FLIP.lang(4) == set()
# Q3  a PDA that never pushes accepts everything it can read
PALL = PDA([("0", "a", "", "0", ""), ("0", "b", "", "0", "")], "0", {"0"})
K3 = classify(lambda w: True, "ab", ("reg", "(a+b)*"))
assert PALL.lang("ab", 8) == set(words("ab", 8)) and K3 == "reg"
# Q5  every pop must push: the stack can never shrink, so only stack-free runs can accept
random.seed(7)
EDGES = [(p, a, pop, q, push) for p in "01" for a in ("", "a") for pop in ("", "x") for q in "01" for push in ("", "x")
         if not (pop and not push)]
same = True
for _ in range(250):
    es = random.sample(EDGES, random.randint(2, 8))
    acc = {s for s in "01" if random.random() < 0.5}
    M = PDA(es, "0", acc)
    N = nfa_from_edges("a", [(p, a, q) for (p, a, pop, q, push) in es if not pop and not push], "0", acc)
    if M.lang("a", 7) != N.lang(7):
        same = False
INF_REG = PDA([("0", "a", "", "0", "")], "0", {"0"}).lang("a", 7) == {"a" * k for k in range(8)}
assert same and INF_REG


PA = PDA([("0", "a", "", "0", "A"), ("0", "", "", "1", ""), ("1", "b", "A", "1", "")], "0", {"1"})
assert PA.lang("ab", 8) == {"a" * n + "b" * n for n in range(5)}
PB = PDA([("0", "a", "", "0", "A"), ("0", "", "", "1", ""), ("1", "b", "A", "1", ""), ("1", "", "", "2", ""), ("2", "c", "A", "2", "")],
         "0", {"0", "1", "2"})
LB = PB.lang("abc", 8)
assert LB == {w for w in words("abc", 8) if re.fullmatch("(a*)(b*)(c*)", w) and w.count("a") == w.count("b") + w.count("c")}
PC = PDA([("0", "", "", "1", "Z"), ("1", "", "Z", "2", ""), ("2", "a", "", "2", "")], "0", {"2"})
assert PC.lang("ab", 7) == {"a" * k for k in range(8)}
PD = PDA([("0", "a", "", "0", "A")], "0", {"0"})
rej_a = not PD.accepts("a") and PD.accepts("a", require_empty=False) and PD.accepts("")
PE = PDA([("0", "a", "", "1", "A"), ("1", "b", "A", "2", "B")], "0", {"2"})
LE = PE.lang("ab", 8)
assert LE == set()



# contains 11 (3 states)
D1 = dfa_table("01", {"0": "0 1", "1": "0 2", "2": "2 2"}, "0", {"2"})
assert D1.lang(8) == {w for w in words("01", 8) if "11" in w}
# ends with 1
D2 = dfa_table("01", {"0": "0 1", "1": "0 1"}, "0", {"1"})
assert D2.lang(8) == {w for w in words("01", 8) if w.endswith("1")}
# even number of 1s
D3 = dfa_table("01", {"0": "0 1", "1": "1 0"}, "0", {"0"})
assert D3.lang(8) == {w for w in words("01", 8) if w.count("1") % 2 == 0}
# does not end with aa  (states: 0 = ends in b / empty, 1 = ends in single a, 2 = ends in aa or more)
D4 = dfa_table("ab", {"0": "1 0", "1": "2 0", "2": "2 0"}, "0", {"0", "1"})
assert D4.lang(8) == {w for w in words("ab", 8) if not w.endswith("aa")}
# number of 1s mod 3
D5 = dfa_table("01", {"0": "0 1", "1": "1 2", "2": "2 0"}, "0", {"0"})
assert all(D5.run(w) == str(w.count("1") % 3) for w in words("01", 8))


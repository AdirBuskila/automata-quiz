# exhaustive facts over every 3-state binary DFA
ALL3 = list(all_dfas(3, "01"))
SIGMA_STAR = [d for d in ALL3 if d.complement().is_empty()]
f_reach_acc = all(d.reachable() <= d.acc for d in SIGMA_STAR)
f_Q_eq_F = all(d.states == d.acc for d in SIGMA_STAR)
f_q1 = all(len(d.states) == 1 for d in SIGMA_STAR)
assert not f_Q_eq_F and not f_q1 and f_reach_acc
long_acc = [d for d in ALL3 if any(d.accepts(w) for w in words("01", 7) if len(w) >= 3)]
g_inf = all(d.is_infinite() for d in long_acc)
g_fin = all(not d.is_infinite() for d in long_acc)
g_empty = all(d.is_empty() for d in long_acc)
g_sigma = all(d.complement().is_empty() for d in long_acc)
assert g_inf and not g_fin

can_F_empty = any(not d.acc for d in ALL3)
can_q0_in_F = any("0" in d.acc for d in ALL3)
can_Q_eq_F = any(d.states == d.acc for d in ALL3)


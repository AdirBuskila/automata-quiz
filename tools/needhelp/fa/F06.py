def rel(r1, r2, alpha):
    return rx_vs_rx(r1, r2, alpha)


def opts_rel(r1, r2, alpha):
    v = rel(r1, r2, alpha)
    return [C("שוות: $L(r_1)=L(r_2)$", v == "eq"), C(r"$L(r_1)\subsetneq L(r_2)$", v == "lt"),
            C(r"$L(r_2)\subsetneq L(r_1)$", v == "gt"), C("אף אחת מהשלוש: אין הכלה בשני הכיוונים", v == "none")]


# lesson facts
assert rel("(1*01*0)*1*", "(1+01*0)*", "01") == "eq"
assert rel("(a+b)*a", "(a+b)(a+b)*", "ab") == "lt"
assert rel("(ab)*", "a*b*", "ab") == "none" and rel("0*+1*", "(0+1)*", "01") == "lt"
assert rel("(a*b)*", "ε+(a+b)*b", "ab") == "eq"


def holds(left, right, samples, alpha="01"):
    return all(rx(left(r), alpha).equiv(rx(right(r), alpha)) for r in samples)


S1 = ["0", "1", "01", "0+1", "ε", "1*0", "(00)"]
I_star = holds(lambda r: f"(({r})*)*", lambda r: f"({r})*", S1)
I_rr = holds(lambda r: f"(({r})({r}))*", lambda r: f"({r})*({r})*", S1)
I_sum = holds(lambda r: f"({r}+(01))*", lambda r: f"({r})*+(01)*", S1)
I_plus = holds(lambda r: f"{r}+({r})({r})", lambda r: f"({r}+{r})({r})", S1)
assert I_star and not I_rr and not I_sum and not I_plus

A1, A2 = "(0+1)*11(0+1)*", "(0+1)*1(0+1)*"
x1, x2 = rx(A1, "01"), rx(A2, "01")


def only2(w):
    return x2.accepts(w) and not x1.accepts(w)


P1, P2 = "(ab)*", "a*b*"
y1, y2 = rx(P1, "ab"), rx(P2, "ab")


def proves_none(u, v):
    return (y1.accepts(u) and not y2.accepts(u) and y2.accepts(v) and not y1.accepts(v)) or \
           (y2.accepts(u) and not y1.accepts(u) and y1.accepts(v) and not y2.accepts(v))



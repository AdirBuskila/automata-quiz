def same(r, auto, alpha):
    """regex r describes exactly the language of the automaton (exact DFA equivalence + all words to 8)"""
    d = auto if isinstance(auto, DFA) else auto.to_dfa()
    x = rx(r, alpha)
    return x.dfa().equiv(d) and x.lang(8) == d.lang(8)


# A1 even number of b
A1 = dfa_table("ab", {"0": "0 1", "1": "1 0"}, "0", {"0"})
# A2 ends with 01
A2 = dfa_table("01", {"0": "1 0", "1": "1 2", "2": "1 0"}, "0", {"2"})
assert A2.lang(8) == {w for w in words("01", 8) if w.endswith("01")}
# A3 epsilon NFA over {a}: lengths 2,4,6,...
A3 = nfa_from_edges("a", [("0", "a", "1"), ("1", "a", "2"), ("2", "", "0")], "0", {"2"})
assert A3.lang(10) == {"a" * k for k in range(2, 11, 2)}
# A4 prefix a, then loops ba | aa | bbb around state 1
A4 = nfa_from_edges("ab", [("0", "a", "1"), ("1", "b", "3"), ("3", "a", "1"), ("1", "a", "4"), ("4", "a", "1"),
                           ("1", "b", "5"), ("5", "b", "6"), ("6", "b", "1")], "0", {"1"})
# A5 number of a's = 1 mod 3
A5 = dfa_table("ab", {"0": "1 0", "1": "2 1", "2": "0 2"}, "0", {"1"})
assert A5.lang(8) == {w for w in words("ab", 8) if w.count("a") % 3 == 1}
assert same("a(ba+aa+bbb)*", A4, "ab")
assert same("(a+ba*b)*", A1, "ab")


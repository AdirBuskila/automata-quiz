def eq_pred(r, pred, alpha):
    return rx(r, alpha).lang(8) == {w for w in words(alpha, 8) if pred(w)}


def eq_rx(r1, r2, alpha):
    return rx(r1, alpha).equiv(rx(r2, alpha))


